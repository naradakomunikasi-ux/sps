import assert from 'node:assert/strict';
import {reconcileZoomEvidence} from '../apps/api/src/zoom-reconciliation.ts';
const person='11111111-1111-4111-8111-111111111111', other='22222222-2222-4222-8222-222222222222';
const e={provider:'ZOOM',status:'PENDING_RECONCILIATION',meetingId:'m1',participantExternalId:'z1',fingerprint:'a'.repeat(64)};
const roster=[{personId:person,meetingId:'m1',externalId:'z1',activeEnrollment:true}];
const test=(payload,rows,known,expected)=>{const d=reconcileZoomEvidence(payload,rows,new Set(known));assert.equal(d.status,expected);assert.equal(d.attendanceMutated,false);return d};
let count=0;
assert.equal(test(e,roster,[],'READY_FOR_REVIEW').personId,person);count++;
test(e,roster,[e.fingerprint],'DUPLICATE');count++;
test(e,[],[],'UNMATCHED');count++;
test(e,[{...roster[0],activeEnrollment:false}],[],'UNMATCHED');count++;
test(e,[{...roster[0],meetingId:'m2'}],[],'UNMATCHED');count++;
test(e,[{...roster[0],externalId:'z2'}],[],'UNMATCHED');count++;
test(e,[...roster,{...roster[0],personId:other}],[],'AMBIGUOUS');count++;
assert.equal(test(e,[...roster,...roster],[],'READY_FOR_REVIEW').personId,person);count++;
test({...e,fingerprint:'x'},roster,[],'INVALID');count++;
test({...e,provider:'OTHER'},roster,[],'INVALID');count++;
test({...e,status:'APPROVED'},roster,[],'INVALID');count++;
test({...e,participantExternalId:''},roster,[],'INVALID');count++;
test(null,roster,[],'INVALID');count++;
test(e,[{...roster[0],personId:'invalid'}],[],'UNMATCHED');count++;
console.log(`PASS ${count}/${count} Zoom reconciliation domain tests (no provider calls, no canonical writes)`);
