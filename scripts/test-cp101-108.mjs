import assert from 'node:assert/strict';
import {createHmac} from 'node:crypto';
import {receiveZoomWebhook} from '../apps/api/src/zoom-webhook-http.ts';
import {readFileSync} from 'node:fs';
let n=0;
const check=(condition,description)=>{assert.ok(condition,description);n++};
const secret='a-provider-secret-long-enough';
const now=1800000000;
const raw=Buffer.from(JSON.stringify({event:'meeting.participant_joined',event_ts:now*1000,payload:{object:{id:'1'}}}));
const stamp=String(now);
const signature='v0='+createHmac('sha256',secret).update(Buffer.concat([Buffer.from(`v0:${stamp}:`),raw])).digest('hex');
const entries=new Set();let calls=[];let released=0;let failInsert=false;
const pool={connect:async()=>({query:async(sql,params)=>{calls.push({sql,params});if(sql==='BEGIN'||sql==='COMMIT'||sql==='ROLLBACK')return {rows:[]};if(failInsert)throw Error('simulated DB fault');const id=params[0];if(entries.has(id))return {rows:[]};entries.add(id);return {rows:[{event_id:id}]};},release:()=>{released++;}})};
const send=(changes={})=>receiveZoomWebhook({pool,rawBody:raw,signature,timestamp:stamp,secret,nowSeconds:now,...changes});
let r=await send();check(r.status===200&&r.body.outcome==='accepted','first request accepted');
check(calls.map(x=>x.sql).includes('BEGIN')&&calls.map(x=>x.sql).includes('COMMIT'),'transaction committed');
check(calls.some(x=>x.sql.includes('ON CONFLICT(event_id) DO NOTHING')),'idempotent insertion');
check(calls.find(x=>x.params)?.params?.length===3,'parameterized write');
check(released===1,'client released');
r=await send();check(r.body.outcome==='duplicate','repeat payload deduplicated');check(released===2,'duplicate releases client');
const before=calls.length;r=await send({signature:'v0='+ '0'.repeat(64)});check(r.status===401,'tampered signature refused');check(calls.length===before,'invalid signature never connects');
r=await send({timestamp:String(now-301)});check(r.status===401,'stale timestamp refused');
r=await send({rawBody:Buffer.alloc(1024*1024+1)});check(r.status===401,'oversized payload refused');
r=await send({rawBody:'not bytes'});check(r.status===400,'parsed body not accepted');
failInsert=true;const raw2=Buffer.from(JSON.stringify({event:'meeting.ended',event_ts:now*1000}));const signature2='v0='+createHmac('sha256',secret).update(Buffer.concat([Buffer.from(`v0:${stamp}:`),raw2])).digest('hex');r=await send({rawBody:raw2,signature:signature2});check(r.status===503,'database failure unavailable');check(calls.some(x=>x.sql==='ROLLBACK'),'failure rolls back');check(released===3,'failed transaction releases');
const main=readFileSync(new URL('../apps/api/src/main.ts',import.meta.url),'utf8');
check(main.includes('rawBody: true'),'Nest raw bytes kept');check(main.includes("@Post('webhook')"),'route mounted');
check(!main.includes('attendance.update'),'no direct canonical attendance update');
console.log(`CP101-108: ${n}/${n} transactional webhook assertions PASS`);
