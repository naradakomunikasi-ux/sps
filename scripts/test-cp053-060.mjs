import assert from 'node:assert/strict';
import { createHmac } from 'node:crypto';
import {verifyZoomWebhook} from '../apps/api/src/zoom-webhook-verification.ts';
let n=0;
function check(condition, description) {assert.ok(condition,description);n++}
const now=1792990000,ts=String(now),secret='test-webhook-secret-24chars';
const body=Buffer.from(JSON.stringify({event:'meeting.participant_joined',event_ts:1792990000000,payload:{object:{id:'123'}}}));
const sign=(b,t=ts,k=secret)=>'v0='+createHmac('sha256',k).update(Buffer.concat([Buffer.from(`v0:${t}:`),b])).digest('hex');
const args={rawBody:body,signature:sign(body),timestamp:ts,secret,nowSeconds:now,previouslySeen:()=>false};
const ok=verifyZoomWebhook(args);
check(ok.ok,'valid signature');
check(ok.ok&&ok.eventId.length===64,'stable event digest');
check(ok.ok&&ok.timestampSeconds===now,'timestamp returned');
check(!verifyZoomWebhook({...args,signature:sign(Buffer.from('other'))}).ok,'modified body rejected');
check(!verifyZoomWebhook({...args,signature:'v0='+ '0'.repeat(64)}).ok,'wrong signature rejected');
check(!verifyZoomWebhook({...args,signature:'v0=oops'}).ok,'invalid signature format rejected');
check(!verifyZoomWebhook({...args,timestamp:'1'}).ok,'invalid timestamp rejected');
check(!verifyZoomWebhook({...args,nowSeconds:now+301}).ok,'stale future clock rejected');
check(!verifyZoomWebhook({...args,nowSeconds:now-301}).ok,'stale past clock rejected');
check(!verifyZoomWebhook({...args,secret:'short'}).ok,'missing/weak config rejected');
check(!verifyZoomWebhook({...args,rawBody:Buffer.alloc(0)}).ok,'empty body rejected');
check(!verifyZoomWebhook({...args,rawBody:Buffer.alloc(1024*1024+1)}).ok,'oversize rejected');
check(!verifyZoomWebhook({...args,rawBody:Buffer.from('not-json'),signature:sign(Buffer.from('not-json'))}).ok,'invalid JSON rejected');
check(!verifyZoomWebhook({...args,previouslySeen:()=>true}).ok,'replay rejected');
const malformed=Buffer.from(JSON.stringify({event:'x',event_ts:'bad'}));
check(!verifyZoomWebhook({...args,rawBody:malformed,signature:sign(malformed)}).ok,'invalid event rejected');
const mismatch=Buffer.from(JSON.stringify({event:'meeting.participant_joined',event_ts:1792990000000}));
check(verifyZoomWebhook({...args,rawBody:mismatch,signature:sign(mismatch)}).ok,'distinct correctly signed request permitted');
console.log(`PASS CP053-060 Zoom webhook verification: ${n}/${n} assertions (pure unit, no HTTP/provider integration)`);
