import assert from 'node:assert/strict';
import {authorize, permissionBundles} from '../apps/api/src/security.ts';
import {stateRegistry,canTransitionState} from '../apps/api/src/state-registry.ts';
import {canTransition} from '../apps/api/src/domain.ts';
let n=0;const check=(name, actual, expected)=>{assert.deepEqual(actual,expected,name);n++};
check('five explicit roles',Object.keys(permissionBundles).length,5);
check('unique grants', Object.values(permissionBundles).every(a=>new Set(a).size===a.length),true);
check('deny unknown role',authorize({personId:'P',activeRole:'ROOT',batchIds:['B']},'profile.read.self',{personId:'P'}),false);
check('deny unknown grant',authorize({personId:'P',activeRole:'ADMIN',batchIds:['B']},'system.write',{batchId:'B'}),false);
check('no undefined resource',authorize({personId:'P',activeRole:'ADMIN',batchIds:['B']},'participant.read.scoped',undefined),false);
check('no null resource',authorize({personId:'P',activeRole:'ADMIN',batchIds:['B']},'participant.read.scoped',null),false);
check('no forged batch role',authorize({personId:'P',activeRole:'PARTICIPANT',batchIds:['B']},'participant.read.scoped',{batchId:'B'}),false);
check('all role permissions classified',Object.values(permissionBundles).flat().every(p=>p.endsWith('.self')||p.endsWith('.scoped')||p.endsWith('.assigned')),true);
check('both lifecycle models',Object.keys(stateRegistry).length,2);
check('batch approved transition',canTransitionState('batch','DRAFT','REGISTRATION_OPEN'),true);
check('batch skip denied',canTransitionState('batch','DRAFT','ACTIVE'),false);
check('batch reverse denied',canTransitionState('batch','ACTIVE','DRAFT'),false);
check('batch terminal state',canTransitionState('batch','ARCHIVED','DRAFT'),false);
check('unknown initial state',canTransitionState('batch','UNKNOWN','ACTIVE'),false);
check('enrollment normal',canTransition('APPLIED','REVIEW'),true);
check('enrollment skip denied',canTransition('APPLIED','COMPLETED'),false);
check('enrollment terminal',canTransition('COMPLETED','ACTIVE'),false);
check('no self transition',canTransition('REVIEW','REVIEW'),false);
console.log(`PASS ${n}/${n} CP022 permission bundle + lifecycle behavioral tests`);
